import os
import sys
import docx
from docx import Document
from docx.shared import Pt, Inches, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls, qn

def build_coursework():
    doc = Document()

    # 1. Параметры страницы по ГОСТ 7.32 (ТИУ)
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)
    section.left_margin = Cm(3.0)
    section.right_margin = Cm(1.5)

    # Настройка колонтитула: номер страницы по центру внизу, первая страница (титульный лист) без номера
    section.different_first_page_header_footer = True
    footer = section.footer
    p_foot = footer.paragraphs[0]
    p_foot.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_foot.paragraph_format.first_line_indent = Cm(0)
    p_foot.paragraph_format.space_before = Pt(0)
    p_foot.paragraph_format.space_after = Pt(0)
    r_foot = p_foot.add_run()
    r_foot.font.name = 'Times New Roman'
    r_foot.font.size = Pt(12)
    r_foot.font.color.rgb = RGBColor(0, 0, 0)
    fld_page = parse_xml(r'<w:fldSimple %s w:instr="PAGE"/>' % nsdecls('w'))
    p_foot._p.append(fld_page)

    # Автоматическое обновление полей (включая оглавление TOC) при открытии документа
    doc.settings.element.append(parse_xml(r'<w:updateFields %s w:val="true"/>' % nsdecls('w')))

    # Настройка базового стиля Normal
    style_normal = doc.styles['Normal']
    style_normal.font.name = 'Times New Roman'
    style_normal.font.size = Pt(14)
    style_normal.font.color.rgb = RGBColor(0, 0, 0)
    style_normal.paragraph_format.line_spacing = 1.5
    style_normal.paragraph_format.space_after = Pt(0)
    style_normal.paragraph_format.space_before = Pt(0)
    style_normal.paragraph_format.first_line_indent = Cm(1.25)
    style_normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    # Стили заголовков Word для динамического TOC
    h1_style = doc.styles['Heading 1']
    h1_style.font.name = 'Times New Roman'
    h1_style.font.size = Pt(16)
    h1_style.font.bold = True
    h1_style.font.color.rgb = RGBColor(0, 0, 0)
    h1_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    h1_style.paragraph_format.space_before = Pt(20)
    h1_style.paragraph_format.space_after = Pt(10)
    h1_style.paragraph_format.first_line_indent = Cm(0)
    h1_style.paragraph_format.keep_with_next = True

    h2_style = doc.styles['Heading 2']
    h2_style.font.name = 'Times New Roman'
    h2_style.font.size = Pt(14)
    h2_style.font.bold = True
    h2_style.font.color.rgb = RGBColor(0, 0, 0)
    h2_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    h2_style.paragraph_format.space_before = Pt(14)
    h2_style.paragraph_format.space_after = Pt(6)
    h2_style.paragraph_format.first_line_indent = Cm(1.25)
    h2_style.paragraph_format.keep_with_next = True

    h3_style = doc.styles['Heading 3']
    h3_style.font.name = 'Times New Roman'
    h3_style.font.size = Pt(14)
    h3_style.font.bold = True
    h3_style.font.italic = True
    h3_style.font.color.rgb = RGBColor(0, 0, 0)
    h3_style.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    h3_style.paragraph_format.space_before = Pt(10)
    h3_style.paragraph_format.space_after = Pt(4)
    h3_style.paragraph_format.first_line_indent = Cm(1.25)
    h3_style.paragraph_format.keep_with_next = True

    for s_name in ['toc 1', 'toc 2', 'toc 3', 'TOC 1', 'TOC 2', 'TOC 3']:
        try:
            st = doc.styles[s_name]
            st.font.name = 'Times New Roman'
            st.font.size = Pt(12)
            st.font.color.rgb = RGBColor(0, 0, 0)
        except Exception:
            pass

    def set_table_borders(table):
        tblPr = table._tbl.tblPr
        borders = parse_xml(
            r'<w:tblBorders %s>'
            r'  <w:top w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:bottom w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:left w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:right w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:insideH w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'  <w:insideV w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
            r'</w:tblBorders>' % nsdecls('w')
        )
        tblPr.append(borders)

    def set_cell_margins(cell, top=100, bottom=100, left=140, right=140):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = parse_xml(
            f'<w:tcMar {nsdecls("w")}>'
            f'<w:top w:w="{top}" w:type="dxa"/>'
            f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
            f'<w:left w:w="{left}" w:type="dxa"/>'
            f'<w:right w:w="{right}" w:type="dxa"/>'
            f'</w:tcMar>'
        )
        tcPr.append(tcMar)

    def add_p(text, bold_prefix=""):
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        if bold_prefix:
            r_pre = p.add_run(bold_prefix)
            r_pre.font.name = 'Times New Roman'
            r_pre.font.size = Pt(14)
            r_pre.font.bold = True
        r = p.add_run(text)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(14)
        return p

    def add_bullet(text, bold_prefix=""):
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.space_before = Pt(0)
        p.paragraph_format.space_after = Pt(0)
        r_b = p.add_run("— ")
        r_b.font.name = 'Times New Roman'
        r_b.font.size = Pt(14)
        if bold_prefix:
            r_pre = p.add_run(bold_prefix)
            r_pre.font.name = 'Times New Roman'
            r_pre.font.size = Pt(14)
            r_pre.font.bold = True
        r = p.add_run(text)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(14)
        return p

    def add_figure_real(image_path, caption, width_cm=7.0):
        if os.path.exists(image_path):
            p_img = doc.add_paragraph()
            p_img.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p_img.paragraph_format.space_before = Pt(8)
            p_img.paragraph_format.space_after = Pt(4)
            p_img.paragraph_format.first_line_indent = Cm(0)
            p_img.add_run().add_picture(image_path, width=Cm(width_cm))

        p_cap = doc.add_paragraph()
        p_cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_cap.paragraph_format.space_before = Pt(2)
        p_cap.paragraph_format.space_after = Pt(10)
        p_cap.paragraph_format.first_line_indent = Cm(0)
        r = p_cap.add_run(caption)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(12)
        r.font.italic = True

    def add_figure_placeholder(caption, description):
        p_box = doc.add_paragraph()
        p_box.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_box.paragraph_format.space_before = Pt(8)
        p_box.paragraph_format.space_after = Pt(4)
        p_box.paragraph_format.first_line_indent = Cm(0)

        t = doc.add_table(rows=1, cols=1)
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        cell = t.cell(0, 0)
        cell.width = Cm(15.0)
        set_cell_margins(cell, top=180, bottom=180, left=180, right=180)

        tcPr = cell._tc.get_or_add_tcPr()
        tcBorders = parse_xml(
            f'<w:tcBorders {nsdecls("w")}>'
            f'<w:top w:val="dashed" w:sz="6" w:space="0" w:color="666666"/>'
            f'<w:bottom w:val="dashed" w:sz="6" w:space="0" w:color="666666"/>'
            f'<w:left w:val="dashed" w:sz="6" w:space="0" w:color="666666"/>'
            f'<w:right w:val="dashed" w:sz="6" w:space="0" w:color="666666"/>'
            f'</w:tcBorders>'
        )
        tcPr.append(tcBorders)

        cp = cell.paragraphs[0]
        cp.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.paragraph_format.line_spacing = 1.15
        cp.paragraph_format.first_line_indent = Cm(0)
        r1 = cp.add_run("[ Место для вставки скриншота консоли ]\n")
        r1.font.name = 'Times New Roman'
        r1.font.size = Pt(11)
        r1.font.bold = True
        r2 = cp.add_run(description)
        r2.font.name = 'Times New Roman'
        r2.font.size = Pt(10)
        r2.font.italic = True

        p_cap = doc.add_paragraph()
        p_cap.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_cap.paragraph_format.space_before = Pt(2)
        p_cap.paragraph_format.space_after = Pt(10)
        p_cap.paragraph_format.first_line_indent = Cm(0)
        r = p_cap.add_run(caption)
        r.font.name = 'Times New Roman'
        r.font.size = Pt(12)
        r.font.italic = True

    # ==========================================
    # ТИТУЛЬНЫЙ ЛИСТ (СТРОГО ПО СТАНДАРТУ ТИУ)
    # ==========================================
    p_top = doc.add_paragraph()
    p_top.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_top.paragraph_format.line_spacing = 1.15
    p_top.paragraph_format.first_line_indent = Cm(0)
    r = p_top.add_run("МИНИСТЕРСТВО НАУКИ И ВЫСШЕГО ОБРАЗОВАНИЯ РОССИЙСКОЙ ФЕДЕРАЦИИ\n"
                      "ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ ВЫСШЕГО ОБРАЗОВАНИЯ\n"
                      "«ТЮМЕНСКИЙ ИНДУСТРИАЛЬНЫЙ УНИВЕРСИТЕТ»\n"
                      "Высшая школа цифровых технологий\n"
                      "Кафедра математики и прикладных информационных технологий")
    r.font.name = 'Times New Roman'
    r.font.size = Pt(11)
    r.font.bold = True

    for _ in range(4):
        p_sp = doc.add_paragraph()
        p_sp.paragraph_format.line_spacing = 1.0
        p_sp.paragraph_format.first_line_indent = Cm(0)

    p_cw = doc.add_paragraph()
    p_cw.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_cw.paragraph_format.first_line_indent = Cm(0)
    r_cw = p_cw.add_run("КУРСОВАЯ РАБОТА\n")
    r_cw.font.name = 'Times New Roman'
    r_cw.font.size = Pt(18)
    r_cw.font.bold = True

    p_sub = doc.add_paragraph()
    p_sub.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_sub.paragraph_format.first_line_indent = Cm(0)
    p_sub.paragraph_format.line_spacing = 1.2
    r_sub = p_sub.add_run("по предмету: Разработка мобильных приложений\n"
                          "на тему: Разработка мобильного приложения для интеллектуального структурирования "
                          "и управления личными планами на основе искусственного интеллекта")
    r_sub.font.name = 'Times New Roman'
    r_sub.font.size = Pt(14)
    r_sub.font.bold = True

    for _ in range(5):
        p_sp2 = doc.add_paragraph()
        p_sp2.paragraph_format.line_spacing = 1.0
        p_sp2.paragraph_format.first_line_indent = Cm(0)

    p_sign = doc.add_paragraph()
    p_sign.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p_sign.paragraph_format.first_line_indent = Cm(0)
    p_sign.paragraph_format.line_spacing = 1.25
    r_sign = p_sign.add_run("Выполнил: студент гр. ПКТб-23-1\n"
                            "Брацун Д.\n\n"
                            "Руководитель:\n"
                            "Спирин И. С.\n")
    r_sign.font.name = 'Times New Roman'
    r_sign.font.size = Pt(13)

    for _ in range(4):
        p_sp3 = doc.add_paragraph()
        p_sp3.paragraph_format.line_spacing = 1.0
        p_sp3.paragraph_format.first_line_indent = Cm(0)

    p_bot = doc.add_paragraph()
    p_bot.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_bot.paragraph_format.first_line_indent = Cm(0)
    r_bot = p_bot.add_run("Тюмень\n2026")
    r_bot.font.name = 'Times New Roman'
    r_bot.font.size = Pt(13)

    doc.add_page_break()

    # ==========================================
    # ОГЛАВЛЕНИЕ (ДИНАМИЧЕСКОЕ ПОЛЕ MICROSOFT WORD)
    # ==========================================
    p_toc_head = doc.add_paragraph()
    p_toc_head.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p_toc_head.paragraph_format.first_line_indent = Cm(0)
    p_toc_head.paragraph_format.space_before = Pt(16)
    p_toc_head.paragraph_format.space_after = Pt(12)
    r_th = p_toc_head.add_run("ОГЛАВЛЕНИЕ")
    r_th.font.name = 'Times New Roman'
    r_th.font.size = Pt(16)
    r_th.font.bold = True

    # Вставка настоящего комплексного поля Word TOC
    p_toc = doc.add_paragraph()
    p_toc.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p_toc.paragraph_format.first_line_indent = Cm(0)
    p_toc.paragraph_format.line_spacing = 1.15
    p_toc.paragraph_format.space_after = Pt(6)

    r_toc = p_toc.add_run()
    r_toc._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="begin"/>' % nsdecls('w')))
    r_toc._r.append(parse_xml(r'<w:instrText %s xml:space="preserve"> TOC \o "1-3" \h \z \u </w:instrText>' % nsdecls('w')))
    r_toc._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="separate"/>' % nsdecls('w')))
    r_toc._r.append(parse_xml(r'<w:fldChar %s w:fldCharType="end"/>' % nsdecls('w')))

    doc.add_page_break()

    # ==========================================
    # ВВЕДЕНИЕ
    # ==========================================
    doc.add_heading("ВВЕДЕНИЕ", level=1)

    add_p("Каждый день современный человек сталкивается с непрерывным и лавинообразным потоком входящей информации: учебные задания, рабочие дедлайны, бытовые обязанности, личные договоренности и внезапно возникающие идеи. В условиях высокой информационной насыщенности человеческий мозг испытывает значительное напряжение. Согласно фундаментальным исследованиям в области когнитивной психологии, объем оперативной памяти ограничен: сознание способно одновременно и безошибочно удерживать в активном фокусе лишь небольшое число объектов. Попытка запомнить десятки разнородных планов приводит к перегрузке, хроническому ощущению тревожности, потере концентрации и развитию прокрастинации. В психологической науке данный феномен подробно описан как эффект незавершенного действия: мозг непрерывно расходует ценные ресурсы внимания на то, чтобы не упустить несделанное дело, что мешает качественному выполнению текущей работы.")

    add_p("Существующие мобильные планировщики, календари и классические списки задач призваны решать указанную проблему, предоставляя инструмент внешней фиксации планов. Однако реальная статистика показывает парадоксальную картину: подавляющее большинство пользователей (до 75–80%) прекращают пользоваться установленными приложениями уже через две-три недели после начала работы. Причина этого кроется в существенном интерфейсном сопротивлении и психологическом барьере традиционных систем.")

    add_p("Чтобы зафиксировать мысль в стандартном планировщике, пользователю приходится брать на себя роль собственного администратора: вручную вводить текст, выбирать проект или список, проставлять приоритеты, настраивать метки, вручную выбирать дату в календаре и выставлять точное время напоминания на системных селекторах. В состоянии усталости или высокой занятости необходимость выполнения этой механической рутины вызывает внутренний протест, в результате чего мысли остаются незафиксированными.")

    add_p("Кроме того, большинство современных коммерческих сервисов невольно транслируют культ жесткой продуктивности. Если человек по объективным причинам не успел выполнить запланированные дела в срок, приложение начинает наказывать его визуальным давлением: задачи окрашиваются в тревожный красный цвет, появляются счетчики просрочки, приходят упрекающие уведомления. Вместо чувства облегчения пользователь начинает испытывать чувство вины за собственную неорганизованность. Единственным психологически комфортным выходом из создавшегося стресса становится удаление приложения со смартфона.")

    add_p("Бурное развитие технологий искусственного интеллекта и больших языковых моделей открывает принципиально новую возможность преодоления этого фундаментального противоречия. Вместо того чтобы принуждать человека к ручному администрированию, интеллектуальная система должна взять всю рутинную обработку входящей информации на себя. Пользователь должен иметь возможность быстро и в свободной форме выговориться голосом или набрать неструктурированный текст, выразив свои мысли, жалобы и эмоции. Задача программного обеспечения — отделить эмоциональный контекст от реальных действий, сформировать емкие названия, самостоятельно определить уровень сложности, извлечь календарные даты и время и разложить дела по полочкам без вмешательства человека.")

    add_p("необходимость устранения высокого психологического и интерфейсного барьера при организации личных планов за счет перекладывания рутины структурирования на алгоритмы искусственного интеллекта, что позволяет человеку мгновенно освобождать память от стресса без чувства вины и без ведения сложного учета.", bold_prefix="Актуальность темы обусловлена: ")

    add_p("спроектировать и разработать мобильное приложение для операционной системы Android, обеспечивающее интеллектуальный семантический разбор неструктурированного потока мыслей с помощью нейросетевых моделей и организацию личных дел с минимальным порогом входа и полным снятием рутинной нагрузки с пользователя.", bold_prefix="Цель курсовой работы — ")

    add_p("Для достижения поставленной цели необходимо решить следующие научно-практические задачи:")
    add_bullet("Исследовать психологические барьеры персонального тайм-менеджмента, феномен когнитивной перегрузки и причины отказа пользователей от классических мобильных планировщиков;")
    add_bullet("Адаптировать методологию организации личных дел для повседневного использования без сложных регламентов и навязчивого культа продуктивности;")
    add_bullet("Разработать правила семантического анализа и регламент обработки естественной речи с помощью больших языковых моделей с получением строго структурированного результата;")
    add_bullet("Спроектировать архитектуру мобильного приложения, локальную реляционную базу данных и структуру взаимосвязей сущностей;")
