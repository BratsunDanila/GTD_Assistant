package com.sbros.app.domain.model

enum class ShelfType {
    SIMPLE_STEPS, // Простые шаги (одиночные действия)
    BIG_THINGS,   // Большие дела (проекты из нескольких шагов)
    WAITING,      // Жду от других (делегировано / ожидание)
    SOMEDAY       // На потом и отдых (идеи, фильмы, хотелки без сроков)
}

enum class EnergyLevel {
    EASY,     // Легкое (бытовуха, покупки, когда нет сил и тупишь)
    FIVE_MIN, // На 5 мин (правило 2-5 минут: быстрые звонки, сообщения)
    FOCUS     // Поработать (требует концентрации, но шаг уже раздроблен до <= 25 мин)
}

enum class ThemePalette {
    SAGE,     // Шалфей — природный спокойный зеленый (по умолчанию)
    CLAY,     // Терракота — теплая глина / песок
    LAVENDER, // Лаванда — спокойный серо-фиолетовый
    OCEAN     // Океан — прохладный мятно-синий
}
